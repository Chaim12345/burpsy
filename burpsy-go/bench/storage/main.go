// Command storage measures the memory, disk and query cost of four storage
// models for captured proxy traffic, under an identical deterministic
// workload. It is a throwaway measurement harness, not part of the product.
//
// Each model runs in its own process (one subcommand), so peak RSS is
// comparable across models. The four models are:
//
//	resident  — bytes copied into the Go heap (core.TrafficStore, in-memory).
//	segment   — bytes appended to segment files AND retained on the heap
//	            (core.NewTrafficStoreWithCaptureDir as currently implemented;
//	            Put does storedRaw = raw, store.go:236).
//	mmap      — bytes appended to one file and read back through a read-only
//	            mmap; the heap holds only index rows. This is the Rust store's
//	            Body::OnDisk model, which the Go port has not yet realised.
//	sqlite    — a Reaper-style store: every exchange materialised as a row in
//	            modernc.org/sqlite, indexed on status and host.
//
// What makes the comparison fair, and what an earlier revision of this file
// got wrong:
//
//   - Every model parses both messages of every exchange exactly once, and
//     reports messages_parsed so that can be checked. The core store parses
//     inside Put; mmap and sqlite previously took their index fields straight
//     from the generator and so were not charged for parsing at all.
//   - Every model materialises exactly the response *body* bytes, reads every
//     one of them, and reports materialised_bytes and an order-independent
//     checksum over them. If those two agree across models, the models did
//     the same work. Previously mmap touched one byte per 4096-byte page —
//     for the median ~1 KB body, a single touch — while sqlite copied whole
//     blobs including headers.
//   - Every timed operation is reported cold (against a dropped page cache)
//     and warm (best of N). Reporting only min-of-N flatters precisely the
//     two models that read from disk, because runs 2..N hit warm cache.
//     caches_dropped records whether the drop actually succeeded, so a warm
//     number is never silently presented as a cold one.
//   - store.Exchanges() allocates and copies the whole pointer slice
//     (store.go:338). That snapshot is hoisted out of the timed region: it is
//     store bookkeeping, not query work.
//   - The post-materialise memory sample does not call runtime.GC() first.
//     Sampling after a forced GC reports the heap the collector just swept
//     and hands pages back to the OS, which is why an earlier revision showed
//     mmap's RSS *falling* after it had faulted pages in.
//
// Each subcommand prints one JSON object on stdout.
package main

