package web

import (
	"encoding/json"
	"fmt"
	"html"
	"net/http"
	"net/url"
	"strings"

	"github.com/burpsy-go/burpsy/internal/core"
)

// ---- CSRF PoC generation -----------------------------------------------------------------------
//
// Burp's Engagement tools turn a captured request into a ready-to-open HTML page that makes a
// browser replay it. The PoC is generated from the exchange's own bytes — method, scheme, host,
// path and urlencoded body parameters — so what the browser submits is what the client sent, not
// an approximation of it. Values are URL-decoded once (the form re-encodes them on submit) and
// HTML-escaped for attribute context, because a value containing `"` or `&` must arrive at the
// target as the operator's value rather than as markup.
//
// Stated limits, carried in the response's notes: only application/x-www-form-urlencoded bodies
// become hidden inputs today. A multipart or raw body is reported honestly instead of being
// embedded half-parsed — a PoC that drops the boundary is not a PoC.

type csrfParam struct {
	Name  string `json:"name"`
	Value string `json:"value"`
}

type csrfView struct {
	Wired  bool        `json:"wired"`
	Method string      `json:"method"`
	Action string      `json:"action"`
	Params []csrfParam `json:"params"`
	HTML   string      `json:"html"`
	Notes  []string    `json:"notes"`
}

func (s *Server) handleCSRF(w http.ResponseWriter, r *http.Request, id core.ExchangeID) {
	ex, err := s.store.GetExchange(id)
	if err != nil {
		http.Error(w, "Exchange not found", http.StatusNotFound)
		return
	}
	msg, err := s.message(uint64(core.MsgOrZero(ex.Request)))
	if err != nil {
		http.Error(w, "Request bytes unavailable", http.StatusNotFound)
		return
	}
	raw := msg.Raw()

	lineEnd := strings.Index(string(raw), "\r\n")
	if lineEnd < 0 {
		http.Error(w, "Request has no readable request line", http.StatusBadRequest)
		return
	}
	parts := strings.SplitN(string(raw[:lineEnd]), " ", 3)
	if len(parts) < 2 {
		http.Error(w, "Request has no readable request line", http.StatusBadRequest)
		return
	}
	method := parts[0]

	scheme := "http"
	if ex.TLS {
		scheme = "https"
	}
	hostPort := ex.Host
	if (scheme == "https" && ex.Port != 443) || (scheme == "http" && ex.Port != 80) {
		hostPort = fmt.Sprintf("%s:%d", ex.Host, ex.Port)
	}
	action := scheme + "://" + hostPort + ex.Path

	headerEnd := strings.Index(string(raw), "\r\n\r\n")
	headers := ""
	body := ""
	if headerEnd >= 0 {
		headers = string(raw[:headerEnd])
		body = string(raw[headerEnd+4:])
	}
	var contentType string
	for _, line := range strings.Split(headers, "\r\n") {
		if len(line) > len("content-type:") && strings.EqualFold(line[:len("content-type:")], "content-type:") {
			contentType = strings.TrimSpace(line[len("content-type:"):])
		}
	}

	params := []csrfParam{}
	notes := []string{}
	if strings.Contains(strings.ToLower(contentType), "application/x-www-form-urlencoded") {
		for _, pair := range strings.Split(body, "&") {
			if pair == "" {
				continue
			}
			name, value, hadValue := strings.Cut(pair, "=")
			name = decodeFormComponent(name)
			value = decodeFormComponent(value)
			_ = hadValue
			params = append(params, csrfParam{Name: name, Value: value})
		}
	} else if strings.TrimSpace(body) != "" {
		notes = append(notes, "request body was not application/x-www-form-urlencoded; no body parameters were embedded, because a dropped multipart boundary is not a proof")
	} else {
		notes = append(notes, "the request carried no form body; the PoC replays through the query string in the action")
	}

	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(csrfView{
		Wired:  true,
		Method: method,
		Action: action,
		Params: params,
		HTML:   buildCSRFHTML(method, action, params),
		Notes:  notes,
	})
}

func decodeFormComponent(raw string) string {
	if decoded, err := url.QueryUnescape(raw); err == nil {
		return decoded
	}
	// A value that does not decode is submitted verbatim rather than dropped: mangling it would put
	// bytes on the wire the operator never captured.
	return raw
}

func buildCSRFHTML(method, action string, params []csrfParam) string {
	var b strings.Builder
	b.WriteString("<html>\n<!-- CSRF PoC - generated by burpsy -->\n<body>\n")
	fmt.Fprintf(&b, "  <form action=\"%s\" method=\"%s\">\n", html.EscapeString(action), html.EscapeString(method))
	for _, p := range params {
		fmt.Fprintf(&b, "    <input type=\"hidden\" name=\"%s\" value=\"%s\" />\n", html.EscapeString(p.Name), html.EscapeString(p.Value))
	}
	b.WriteString("    <input type=\"submit\" value=\"Submit request\" />\n")
	b.WriteString("  </form>\n")
	b.WriteString("  <script>\n")
	b.WriteString("    history.pushState('', '', '/');\n")
	b.WriteString("    document.forms[0].submit();\n")
	b.WriteString("  </script>\n")
	b.WriteString("</body>\n</html>\n")
	return b.String()
}
