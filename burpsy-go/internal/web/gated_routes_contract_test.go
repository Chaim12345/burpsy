// The gated-route contract between the gate and the console (burpsy-react-ui-gatecontract).
//
// Two resolvers decide which manifest pattern a path belongs to: routeRiskFor here, which the gate
// enforces, and manifestPatternFor in ui/src/lib/api.ts, which decides whether the console mints a
// confirmation before it sends. They are separate code in separate languages, and when they disagree
// the console sends an unconfirmed call to a gated route and gets a 428, or mints for the wrong
// pattern and gets its token refused — the Sequencer stop/pause/resume 400 of PR #363, which only an
// ad-hoc cross-check found.
//
// The fixture is the server's answer for a fixed set of paths, written by this file and checked in.
// TestGatedRouteContractFixtureIsCurrent fails when the server's answer moves away from the fixture;
// gated-routes.contract.test.ts fails when the client's answer does. Either side drifting fails CI.

// gatedContractFixture is the checked-in fixture's path, relative to this package.
const gatedContractFixture = "ui/src/lib/gated-routes.contract.json"

// gatedContractRegen is the command that rewrites the fixture, quoted in every failure.
const gatedContractRegen = "cd burpsy-go && BURPSY_UPDATE_GATE_CONTRACT=1 go test ./internal/web -run TestGatedRouteContractFixtureIsCurrent -count=1"

// gatedContractEntry is one path and the server's resolution of it. Key is null when routeRiskFor
// matches nothing: the gate skips the mux fallthrough "/", which the client's table does carry, so
// the UI test reads null as "/" — both ungated — and says so.
type gatedContractEntry struct {
	Path  string  `json:"path"`
	Key   *string `json:"key"`
	Gated bool    `json:"gated"`
}

type gatedContract struct {
	Comment    string               `json:"comment"`
	Regenerate string               `json:"regenerate"`
	Patterns   []string             `json:"patterns"`
	Paths      []gatedContractEntry `json:"paths"`
}

// fillManifestPattern turns a manifest pattern into a requestable path: every "{name}" and
// "{name...}" segment becomes the sample segment "w", and the "{$}" anchor is dropped.
func fillManifestPattern(pattern string) string {
	pattern = strings.TrimSuffix(pattern, "{$}")
	segs := strings.Split(pattern, "/")
	for i, s := range segs {
		if strings.HasPrefix(s, "{") && strings.HasSuffix(s, "}") {
			segs[i] = "w"
		}
	}
	return strings.Join(segs, "/")
}

// gatedContractPaths is every manifest pattern filled, plus its /extra, /extra/more and
// trailing-slash variants, deduplicated and sorted.
func gatedContractPaths() []string {
	seen := map[string]bool{}
	var out []string
	add := func(p string) {
		if p != "" && !seen[p] {
			seen[p] = true
			out = append(out, p)
		}
	}
	for pattern := range manifest {
		filled := fillManifestPattern(pattern)
		bare := strings.TrimSuffix(filled, "/")
		add(filled)
		add(bare + "/extra")
		add(bare + "/extra/more")
		if strings.HasSuffix(filled, "/") {
			add(bare)
		} else {
			add(filled + "/")
		}
	}
	sort.Strings(out)
	return out
}

// buildGatedContract is the server's resolution of every contract path, rendered deterministically.
func buildGatedContract() ([]byte, error) {
	c := gatedContract{
		Comment: "GENERATED by gated_routes_contract_test.go (burpsy-react-ui-gatecontract): the gate's routeRiskFor " +
			"resolution of every manifest pattern filled with sample segments, plus /extra, /extra/more and trailing-slash " +
			"variants. gated-routes.contract.test.ts asserts manifestPatternFor agrees. Do not edit; regenerate.",
		Regenerate: gatedContractRegen,
	}
	for pattern := range manifest {
		c.Patterns = append(c.Patterns, pattern)
	}
	sort.Strings(c.Patterns)
	for _, path := range gatedContractPaths() {
		e := gatedContractEntry{Path: path}
		if key, risk, ok := routeRiskFor(path); ok {
			e.Key = &key
			e.Gated = needsConfirmation(risk)
		}
		c.Paths = append(c.Paths, e)
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", " ")
	if err := enc.Encode(c); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func TestGatedRouteContractFixtureIsCurrent(t *testing.T) {
	want, err := buildGatedContract()
	if err != nil {
		t.Fatalf("render the contract: %v", err)
	}
	if os.Getenv("BURPSY_UPDATE_GATE_CONTRACT") == "1" {
		if err := os.WriteFile(gatedContractFixture, want, 0o644); err != nil {
			t.Fatalf("write %s: %v", gatedContractFixture, err)
		}
		t.Logf("wrote %s", gatedContractFixture)
		return
	}
	got, err := os.ReadFile(gatedContractFixture)
	if err != nil {
		t.Fatalf("read %s: %v\nregenerate with: %s", gatedContractFixture, err, gatedContractRegen)
	}
	if bytes.Equal(got, want) {
		return
	}
	// Name the first entries that moved, so the failure says what drifted and not only that it did.
	var have, need gatedContract
	if json.Unmarshal(got, &have) != nil || json.Unmarshal(want, &need) != nil {
		t.Fatalf("%s is stale or malformed.\nregenerate with: %s", gatedContractFixture, gatedContractRegen)
	}
	str := func(k *string) string {
		if k == nil {
			return "<none>"
		}
		return *k
	}
	old := map[string]gatedContractEntry{}
	for _, e := range have.Paths {
		old[e.Path] = e
	}
	var diffs []string
	for _, e := range need.Paths {
		o, ok := old[e.Path]
		switch {
		case !ok:
			diffs = append(diffs, "new path "+e.Path)
		case str(o.Key) != str(e.Key) || o.Gated != e.Gated:
			diffs = append(diffs, e.Path+": fixture "+str(o.Key)+" gated="+boolWord(o.Gated)+", server now "+str(e.Key)+" gated="+boolWord(e.Gated))
		}
		delete(old, e.Path)
	}
	for p := range old {
		diffs = append(diffs, "removed path "+p)
	}
	sort.Strings(diffs)
	if len(diffs) > 20 {
		diffs = append(diffs[:20], "...")
	}
	t.Fatalf("%s is stale: the server's route resolution no longer matches the checked-in contract.\n%s\n"+
		"If the change is intended, regenerate with: %s\nand run `bun test src/lib/gated-routes.contract.test.ts` "+
		"in internal/web/ui so the client is checked against the new answer.",
		gatedContractFixture, strings.Join(diffs, "\n"), gatedContractRegen)
}

func boolWord(b bool) string {
	if b {
		return "true"
	}
	return "false"
}

// The contract is only worth what its path set covers. A floor, so a generator that silently
// produced a handful of paths cannot keep both halves green.
func TestGatedRouteContractCoversTheManifest(t *testing.T) {
	paths := gatedContractPaths()
	if len(paths) < 3*len(manifest) {
		t.Fatalf("%d contract paths for %d manifest patterns: the generator lost variants", len(paths), len(manifest))
	}
	gated := 0
	for _, p := range paths {
		if _, r, ok := routeRiskFor(p); ok && needsConfirmation(r) {
			gated++
		}
	}
	if gated == 0 || gated == len(paths) {
		t.Fatalf("%d of %d contract paths gated: the fixture would not distinguish gated from ungated", gated, len(paths))
	}
}
