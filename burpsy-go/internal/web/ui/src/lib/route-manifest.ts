/**
 * Read the Go route manifest (internal/web/route_manifest.go) and the confirmation policy
 * (needsConfirmation in internal/web/agent_tools.go) into the table the console's api client gates
 * on (burpsy-react-ui-p1uz).
 *
 * Pure string functions so the same parse serves the generator (scripts/gen-gated-routes.ts) and the
 * drift test (gated-routes.test.ts): a route added or reclassified in Go without regenerating
 * src/lib/gated-routes.ts fails `bun test src/lib`, which is what stops a new gated route from
 * shipping with a console that sends it bare and gets 428.
 */

/** Go source with `//` line comments removed, so prose naming a risk class is not read as one. */
function stripLineComments(source: string): string {
 return source
  .split("\n")
  .map((line) => {
   // A `//` inside a string literal ("http://…") is not a comment. The manifest's strings never
   // contain a quote-escaped `//`, so tracking quote parity is enough here.
   let inString = false;
   for (let i = 0; i < line.length - 1; i += 1) {
    const c = line[i];
    if (c === "\\") {
     i += 1;
     continue;
    }
    if (c === '"' || c === "`") inString = !inString;
    if (!inString && c === "/" && line[i + 1] === "/") return line.slice(0, i);
   }
   return line;
  })
  .join("\n");
}

/** The risk classes needsConfirmation answers true for. */
export function parseGatedRiskClasses(agentToolsGo: string): string[] {
 const source = stripLineComments(agentToolsGo);
 const fn = /func needsConfirmation\([^)]*\) bool \{([\s\S]*?)\n\}/.exec(source);
 if (!fn?.[1]) throw new Error("needsConfirmation not found in agent_tools.go");
 const trueCase = /case ([^:]+):\s*return true/.exec(fn[1]);
 if (!trueCase?.[1]) throw new Error("needsConfirmation has no `case …: return true`");
 return trueCase[1].split(",").map((name) => name.trim()).filter(Boolean).sort();
}

/** Every manifest pattern with its risk class, in source order. */
export function parseManifestRisks(routeManifestGo: string): { pattern: string; risk: string }[] {
 const source = stripLineComments(routeManifestGo);
 const start = source.indexOf("var manifest = map[string]route{");
 if (start < 0) throw new Error("var manifest not found in route_manifest.go");
 const end = source.indexOf("\n}\n", start);
 const body = source.slice(start, end < 0 ? undefined : end);
 // A key opens a line, or follows the previous entry's closing brace on the same line
 // (`}, "/reissue/": {` — the manifest has one).
 const keys = [...body.matchAll(/(?:^\t|\},[ \t]*)"(\/[^"]*)": \{/gm)];
 return keys.map((match, i) => {
  const from = (match.index ?? 0) + match[0].length;
  const to = keys[i + 1]?.index ?? body.length;
  const risks = [...body.slice(from, to).matchAll(/risk:\s*(risk\w+)/g)].map((m) => m[1]);
  if (risks.length !== 1) throw new Error(`manifest entry ${match[1]} has ${risks.length} risk classes, want 1`);
  return { pattern: match[1] ?? "", risk: risks[0] ?? "" };
 });
}

/** pattern → whether a mutating call on it needs a confirmation, for every manifest pattern. */
export function gatedTable(routeManifestGo: string, agentToolsGo: string): Record<string, boolean> {
 const gated = new Set(parseGatedRiskClasses(agentToolsGo));
 const out: Record<string, boolean> = {};
 for (const { pattern, risk } of parseManifestRisks(routeManifestGo)) out[pattern] = gated.has(risk);
 return out;
}

/** pattern → risk class, for every manifest pattern. The console's REST-API inventory reads this so
 *  the page cannot drift from the routes the server actually classifies (burpsy-react-ui-wt0r). */
export function riskTable(routeManifestGo: string): Record<string, string> {
 const out: Record<string, string> = {};
 for (const { pattern, risk } of parseManifestRisks(routeManifestGo)) out[pattern] = risk;
 return out;
}

/** The generated risk-inventory module, sorted so a regeneration diff shows only real changes. */
export function renderRouteRiskModule(table: Record<string, string>): string {
 const rows = Object.keys(table)
  .sort()
  .map((pattern) => ` ${JSON.stringify(pattern)}: ${JSON.stringify(table[pattern])},`)
  .join("\n");
 return `// GENERATED by scripts/gen-gated-routes.ts from internal/web/route_manifest.go.
// Do not edit: run \`bun run gen:gated-routes\`. src/lib/gated-routes.test.ts fails when this drifts.
//
// Every manifest pattern mapped to the risk class the server assigns it. The REST-API settings page
// (burpsy-react-ui-wt0r) reads this to show an operator what their console exposes to the network,
// from the same manifest route_manifest_test.go asserts against.
export const ROUTE_RISK: Readonly<Record<string, string>> = {
${rows}
};
`;
}

/** The generated module's source, sorted so a regeneration diff shows only real changes. */
export function renderGatedRoutesModule(table: Record<string, boolean>): string {
 const rows = Object.keys(table)
  .sort()
  .map((pattern) => ` ${JSON.stringify(pattern)}: ${table[pattern] ? "true" : "false"},`)
  .join("\n");
 return `// GENERATED by scripts/gen-gated-routes.ts from internal/web/route_manifest.go and
// needsConfirmation (internal/web/agent_tools.go). Do not edit: run \`bun run gen:gated-routes\`.
// src/lib/gated-routes.test.ts fails when this drifts from the Go source.
//
// Every manifest pattern, mapped to whether a mutating call on it must carry a confirmation token.
// All patterns — not only the gated ones — because the gate resolves a path by LONGEST match over
// the whole manifest, and an ungated pattern can be the longest match under a gated one.
export const ROUTE_GATED: Readonly<Record<string, boolean>> = {
${rows}
};
`;
}
