#!/usr/bin/env python3
"""Generate internal/scanner/catalog_data.go from Burp's shipped KnowledgeBase.

    python3 internal/scanner/tools/gen_catalog.py internal/scanner/catalog_data.go

Source: the 183 `resources/KnowledgeBase/Issues/*.json` files from the Burp Suite 2026.7.1
jar, as extracted by the teardown to /root/burp-re/out/scanner_spec/issues/. Set BURP_ISSUES_SRC
to another extraction of the same resource directory if that tree is not present.

Mechanical transcription only — no field is synthesised, reworded, or defaulted, and a field
absent in the source stays absent in the output. The generator exits non-zero rather than emit
anything if the source stops matching its assumptions (183 files, unique filename-encoded IDs,
IDs that fit in u32), because the alternative is a catalog that quietly disagrees with the data
it claims to transcribe.

This is the Go-port twin of crates/scanner/tools/gen_catalog.py. The two must not drift: any
change to the source assumptions or the emitted field set belongs in both files.
"""
import glob
import json
import os
import sys

SRC = os.environ.get("BURP_ISSUES_SRC", "/root/burp-re/out/scanner_spec/issues")
OUT = sys.argv[1]

SEV = {"HIGH": "high", "MEDIUM": "medium", "LOW": "low", "INFO": "info"}


def lit(s):
    """A Go string literal holding exactly `s`.

    Prefers a raw (backtick) string so embedded HTML stays readable in the generated file; falls
    back to an escaped interpreted literal when the text contains something a raw string cannot
    hold verbatim (a backtick or a carriage return).
    """
    if "\r" in s or "`" in s or "\x00" in s:
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace(
            "\r", "\\r"
        ).replace("\n", "\\n") + '"'
    return "`" + s + "`"


def main():
    files = sorted(glob.glob(os.path.join(SRC, "*.json")))
    if len(files) != 183:
        sys.exit(f"expected 183 issue definitions, found {len(files)}")

    issues = []
    for f in files:
        d = json.load(open(f, encoding="utf-8"))
        # The filename encodes the ID in hex (00100200_SqlInjection.json => 0x00100200). That
        # encoding is unique across all 183 files; the JSON `typeIndex` field is not — two files
        # carry a stale value that duplicates another issue's ID. Both are kept verbatim.
        # webIntro is dropped: null in 179 of 183 and duplicative of `description` in the rest.
        remediation = d["remediation"] or ""
        issues.append(
            {
                "type_index": int(os.path.basename(f).split("_")[0], 16),
                "declared_type_index": d["typeIndex"],
                "name": d["name"],
                "severity": SEV[d["typicalSeverity"]],
                "description": d["description"],
                "remediation": remediation,
                "references": d["references"] or [],
                "classifications": d["vulnerabilityClassifications"] or [],
            }
        )
    issues.sort(key=lambda i: i["type_index"])
    idx = [i["type_index"] for i in issues]
    if len(set(idx)) != len(idx):
        sys.exit("filename-encoded type index is not unique — binary search would be unsound")
    if max(idx) > 0xFFFFFFFF:
        sys.exit("a type index does not fit in u32")

    n_dis = sum(1 for i in issues if i["type_index"] != i["declared_type_index"])
    n_rem = sum(1 for i in issues if i["remediation"])
    n_ref = sum(len(i["references"]) for i in issues)
    n_cls = sum(len(i["classifications"]) for i in issues)

    w = []
    p = w.append
    p("// Code generated by tools/gen_catalog.py; DO NOT EDIT.")
    p("//")
    p("// Burp's shipped issue catalog, transcribed. **Generated — do not edit by hand.**")
    p("//")
    p("// Source: `resources/KnowledgeBase/Issues/*.json` from the Burp Suite 2026.7.1 jar,")
    p("// extracted to `/root/burp-re/out/scanner_spec/issues/` by the teardown. Regenerate with")
    p("// `python3 internal/scanner/tools/gen_catalog.py internal/scanner/catalog_data.go`.")
    p("//")
    p(f"// {len(issues)} definitions; {n_rem} carry a remediation ({len(issues) - n_rem} are null in")
    p("// the source and stay empty); " + f"{n_ref} references; {n_cls} vulnerability classifications.")
    p("// There is no CVSS data anywhere in the shipped catalog, so no CVSS field exists here.")
    p("//")
    p("// `TypeIndex` is the ID encoded in the filename, which is unique across all 183 files.")
    p(f"// `DeclaredTypeIndex` is the `typeIndex` field inside the JSON body; it disagrees in")
    p(f"// {n_dis} of {len(issues)} cases, where the stale value duplicates another issue's ID. Both are")
    p("// kept verbatim rather than reconciled — see catalog_test.go.")
    p("//")
    p("// Sorted by TypeIndex so ByTypeIndex can binary-search it.")
    p("package scanner")
    p("")
    p("// The generator's own counts, surfaced through Provenance so a report can state them.")
    p("var (")
    p(f"\tcatalogMetaIssues       = {len(issues)}")
    p(f"\tcatalogMetaWithRemed    = {n_rem}")
    p(f"\tcatalogMetaWithoutRemed = {len(issues) - n_rem}")
    p(")")
    p("")
    p("var catalogData = []IssueDefinition{")
    for i in issues:
        p("\t{")
        p(f"\t\tTypeIndex:         {i['type_index']},")
        p(f"\t\tDeclaredTypeIndex: {i['declared_type_index']},")
        p(f"\t\tName:              {lit(i['name'])},")
        p(f"\t\tTypicalSeverity:   \"{i['severity']}\",")
        p(f"\t\tDescription:       {lit(i['description'])},")
        if i["remediation"]:
            p(f"\t\tRemediation:       {lit(i['remediation'])},")
        if not i["references"]:
            p("\t\tReferences:        []Reference{},")
        else:
            p("\t\tReferences:        []Reference{")
            for r in i["references"]:
                p(f"\t\t\t{{Title: {lit(r['title'])}, URL: {lit(r['url'])}}},")
            p("\t\t},")
        if not i["classifications"]:
            p("\t\tClassifications:   []Classification{},")
        else:
            p("\t\tClassifications:   []Classification{")
            for c in i["classifications"]:
                p(f"\t\t\t{{Title: {lit(c['title'])}, URL: {lit(c['url'])}}},")
            p("\t\t},")
        p("\t},")
    p("}")
    p("")

    open(OUT, "w", encoding="utf-8").write("\n".join(w))
    print(
        f"wrote {OUT}: {len(issues)} issues, {n_rem} with remediation, "
        f"{n_ref} refs, {n_cls} classifications, {os.path.getsize(OUT)} bytes"
    )


main()
